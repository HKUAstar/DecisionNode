// HK协议完整数据帧 (82字节)
struct MCUDataFrame
{
    HKFrameHeader header;     // 0-8: 帧头 (9字节)
    HKGameData data;          // 9-77: 数据 (69字节)
    uint16_t packet_crc16;    // 78-79: 数据CRC16
    uint8_t trailer[2];       // 80-81: 帧尾 'K', 'H'
} __attribute__((packed));

